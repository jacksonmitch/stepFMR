#' Fit a Finite Mixture Regression via the Stepwise WEST Procedure
#'
#' Fits a finite mixture regression model to \code{data} using the stepwise
#' procedure to select which covariates are relevant, and whether each relevant
#' covariate's effect is homogeneous or
#' heterogeneous. Supports Gaussian, Poisson, and binomial responses.
#' Estimation is performed via an EM algorithm, with weighted least squares
#' (or IRWLS for non-Gaussian families) in the M-step.
#'
#' @details
#' Because the mixture order \eqn{G} is unknown, the
#' significance of a covariate is assessed at every candidate \eqn{G}
#' in \code{2:G_max} and the per-\eqn{G} likelihood-ratio p-values are
#' combined into a single weighted sum \eqn{p_0}-value, with weights proportional to
#' \eqn{\exp(-\mathrm{BIC}_G / 2)}. This is the weighted significance test
#' (WEST), which will be used in every step and applied to every candidate covariate.
#' In the forward direction, the candidate covariate with the smallest weighted
#' \eqn{p_0}-value is added at each step if that \eqn{p_0}-value is below \code{alpha}. In the
#' backward direction, the candidate covariate with the largest weighted \eqn{p_0}-value is
#' removed at each step if that \eqn{p_0}-value is greater than \code{alpha}. The search
#' stops when no candidate covariates are eligible to be added or removed. In effect
#' determination, the forward direction starts with every covariate homogeneous and each
#' covariate is tested against the alternative that it is heterogeneous, and the
#' backward direction starts with every covariate heterogeneous and covariate is
#' tested against the alternative that it is homogeneous The significance level
#' is set through \code{\link{fmr_control}}, and search directions are set with the
#' \code{direction} argument.
#'
#' Two searches can be run, in this order:
#' \enumerate{
#'   \item \strong{Variable selection}: which covariates have any effect on
#'   the response.
#'   \item \strong{Effect determination}: for the selected covariates,
#'   whether the effect is heterogeneous (a separate coefficient in every
#'   component) or homogeneous (one coefficient shared by all components).
#' }
#' Upon the completion of the procedure, the mixture order is selected by the model
#' with the lowest BIC.
#'
#' For \code{family = "binomial"}, the response may be
#' \code{cbind(successes, failures)} or a 0/1 vector. A 0/1 response issues
#' a warning because binary responses carry little information about
#' component membership. The column name \code{.binom_size} is reserved.
#'
#' @param formula A formula object (e.g., y ~ x1 + x2) specifying the model.
#' @param data A data.frame containing the variables in the formula.
#' @param G_max An integer (>= 2) specifying the maximum order. Models with \code{2:G_max} components are fit.
#'  Default is 4.
#' @param family A character string, one of \code{"gaussian"},
#'  \code{"poisson"}, or \code{"binomial"}, specifying the response
#'  distribution. Default is \code{"gaussian"}.
#' @param procedure A character string specifying which procedure(s) to run:
#'  \code{"variables"} (variable selection only), \code{"effects"}
#'  (effect determination only, on all covariates in \code{formula}), or
#'  \code{"complete"} (variable selection followed by effect determination
#'  on the selected covariates). Default is \code{"complete"}.
#' @param direction A character vector of length one or two, where each
#'  element is either \code{"forward"} or \code{"backward"}. A single value
#'  is used for both procedures. With two elements, the first sets variable
#'  selection and the second sets effect determination. Default is
#'  \code{"forward"}.
#' @param control A control object of class "FMRControl" generated by
#'  \code{\link{fmr_control}}. Default is \code{fmr_control()}.
#'
#' @return A list of class \code{stepFMR} containing:
#'  \item{call}{The matched call.}
#'  \item{formula}{The model formula. For binomial responses the response
#'  is reduced to the success count (the trial counts are carried
#'  internally).}
#'  \item{family}{The response family used, one of
#'  \code{"gaussian"}, \code{"poisson"}, or \code{"binomial"}.}
#'  \item{procedure}{Which procedure(s) were run: \code{"variables"},
#'  \code{"effects"}, or \code{"complete"}.}
#'  \item{G_values}{The candidate numbers of mixture components
#'  searched (\code{2:G_max}).}
#'  \item{best_fit}{The fit (an object of class \code{fit_fmr})
#'  at the BIC-optimal number of components for the final model.}
#'  \item{variable_selection}{An object of class
#'  \code{select_variables} recording the selected covariates, or
#'  \code{NULL} if \code{procedure} did not include \code{"variables"}.
#'  Use \code{\link{print_steps}} to see the step-by-step search log.}
#'  \item{effect_determination}{An object of class
#'  \code{determine_effects} recording which covariates were
#'  heterogeneous vs. homogeneous, or \code{NULL} if \code{procedure} did
#'  not include \code{"effects"}. Pass this to
#'  \code{\link{print_steps}} to see the
#'  step-by-step search log.}
#'
#' @references Gan, C., Chen, J. and Feng, Z. (2024). Tests of covariate effects
#'  under finite Gaussian mixture regression models. \emph{Journal of Applied
#'  Statistics}, 52(8), 1571-1593. \doi{10.48550/arXiv.2611.15978}
#'
#' @seealso \code{\link{fmr_control}} for tuning parameters,
#'  \code{\link{fitFMR}} to fit a model without selection,
#'  \code{\link{simulate_fmr}} for simulation,
#'  \code{\link{match_groups}} for label matching, and
#'  \code{\link{print_steps}} for the search logs.
#'
#' @export
#'
#' @examples
#' set.seed(1)
#'
#' # Simulate data
#' n <- 200
#' pi <- c(0.2, 0.3, 0.5)
#' z <- sample(1:3, n, replace = TRUE, prob = pi)
#' x1 <- rnorm(n)
#' x2 <- rnorm(n)
#' x3 <- rnorm(n)
#' x4 <- rnorm(n)
#'
#' # True parameters for 3 group mixture model
#' # x1 and x3 are heterogeneous, x2 is homogeneous and x4 has no effect
#' beta <- rbind(
#'   g1 = c(intercept = -4, x1 = -3, x2 = 1.5, x3 = 2, x4 = 0),
#'   g2 = c(intercept = 0, x1 = 1, x2 = 1.5, x3 = -1, x4 = 0),
#'   g3 = c(intercept = 4, x1 = 3, x2 = 1.5, x3 = 0.5, x4 = 0)
#' )
#' sigma <- c(1, 0.5, 2)
#'
#' # Generate linear predictor and corresponding response y
#' eta <- beta[z, "intercept"] + beta[z, "x1"] * x1 + beta[z, "x2"] * x2 +
#'   beta[z, "x3"] * x3 + beta[z, "x4"] * x4
#' y <- rnorm(n, mean = eta, sd = sigma[z])
#' dat <- data.frame(y = y, x1 = x1, x2 = x2, x3 = x3, x4 = x4)
#'
#' # Perform the stepwise procedure in parallel
#' stepFMR(formula = y ~ x1 + x2 + x3 + x4, data = dat, G_max = 3,
#'         control = fmr_control(parallel = TRUE))
#'
stepFMR <- function(
  formula,
  data,
  G_max = 4,
  family = "gaussian",
  procedure = "complete",
  direction = "forward",
  control = fmr_control()
) {
  collection <- checkmate::makeAssertCollection()
  checkmate::assert_formula(formula, add = collection)
  checkmate::assert_data_frame(data, add = collection)
  if (!isTRUE(checkmate::check_int(G_max, lower = 2))) {
    collection$push(sprintf(
      "Maximum number of Components/Groups (G_max) must be >= 2 (received: %s)."
      , G_max))
  }
  checkmate::assert_choice(family,
    choices = c("gaussian", "poisson", "binomial"),
    add = collection
  )
  checkmate::assert_choice(procedure,
    choices = c("complete", "variables", "effects"),
    add = collection
  )
  checkmate::assert_character(direction,
    min.len = 1, max.len = 2, any.missing = FALSE, add = collection
  )
  checkmate::assert_subset(direction,
    choices = c("forward", "backward"), add = collection
  )
  checkmate::assert_class(control, "FMRControl", add = collection)

  if (!collection$isEmpty()) {
    err_messages <- paste0("- ", collection$getMessages(), collapse = "\n")
    stop(err_messages, call. = FALSE)
  }

  if (isTRUE(control$parallel)) {
    old_plan <- future::plan(future::multisession)
    on.exit({future::plan(old_plan)}, add = TRUE)
  }

  formula <- stats::formula(stats::terms(formula, data = data))
  if (procedure == "effects" && length(get_predictors(formula)) == 0L)
    stop("Effect determination requires at least one predictor.", call. = FALSE)

  if (family == "binomial") {
    coerced <- coerce_binomial_formula(formula, data)
    formula <- coerced$formula
    data <- coerced$data
  } else {
    response <- formula[[2]]
    if (is.call(response) && identical(response[[1]], as.name("cbind"))){
      stop("Given formula contains a cbind response, which is",
           "only supported for the binomial family", call. = FALSE)
    }
  }

  G_values <- seq(2, G_max)
  # Create internal model
  model <- FMRModel$new(
    formula = formula,
    data = data,
    G_values = G_values,
    family = family,
    control = control
  )

  variable_selection <- NULL
  effect_determination <- NULL
  best_fit <- NULL

  if (procedure %in% c("complete", "variables")) {
    variable_selection <- quiet_interrupt(select_variables(
      model = model,
      direction = direction[1]
    ))
    if (control$verbose) {
      cli::cli_alert_success(
        "Variables selected: {format_none(variable_selection$selected)}"
      )
    }

    final_fits <- variable_selection$final_fits
  }
  if (procedure %in% c("complete", "effects")) {
    effect_predictors <- if (!is.null(variable_selection)) {
      variable_selection$selected
    } else {
      model$predictors
    }
    if (length(effect_predictors) > 0L) {
      effect_determination <- quiet_interrupt(determine_effects(
        model = model,
        direction = direction[min(2, length(direction))],
        predictors = effect_predictors
      ))
      if (control$verbose) {
        cli::cli_alert_success(paste0(
          "Heterogeneous: {format_none(effect_determination$heterogeneous)}",
          " | Homogeneous: {format_none(effect_determination$homogeneous)}"
        ))
      }

      final_fits <- effect_determination$final_fits
    }
  }

  best_fit <- select_best_G(final_fits, criterion = "bic")

  # Count each baseline and candidate fit once, excluding repeated shared fits.
  convergence_fits <- list()
  for (stage in compact(list(variable_selection, effect_determination))) {
    steps <- stage$steps
    if (length(steps) == 0L) {
      convergence_fits <- c(convergence_fits, stage$final_fits)
      next
    }
    convergence_fits <- c(convergence_fits, steps[[1]]$tests[[1]]$shared_fits)
    for (step in steps) {
      for (test in step$tests) {
        convergence_fits <- c(convergence_fits, test$candidate_fits)
      }
    }
  }
  warn_fit_convergence(convergence_fits, best_fit)

  out <- list(
    call = match.call(),
    formula = formula,
    family = family,
    procedure = procedure,
    G_values = G_values,
    best_fit = best_fit,
    variable_selection = variable_selection,
    effect_determination = effect_determination
  )

  class(out) <- "stepFMR"
  out
}
