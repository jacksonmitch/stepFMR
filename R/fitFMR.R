#' Fit a Finite Mixture Regression Model
#'
#' Fits finite mixture regression models with a user-specified structure:
#' you choose which predictors have a common (homogeneous) effect and which
#' numbers of components to fit. No variable selection or effect testing is
#' done. Use \code{\link{stepFMR}} for that.
#'
#' @details
#' Every predictor in \code{formula} is included. By default each predictor
#' has a separate coefficient in every component (heterogeneous). Predictors
#' named in \code{common} instead share one coefficient across all components
#' (homogeneous). The intercept is always component-specific.
#'
#' One model is fit for each value of \code{G} (sequentially) and the model
#' with the lowest BIC is reported as the selected fit. Use a single value
#' of \code{G} if you already know the number of components.
#'
#' For \code{family = "binomial"}, the response may be
#' \code{cbind(successes, failures)} or a 0/1 vector. A 0/1 response issues
#' a warning because binary responses carry little information about
#' component membership. The column name \code{.binom_size} is reserved.
#'
#' @param formula A formula object (e.g., y ~ x1 + x2) specifying the model.
#' @param data A data.frame containing the variables in the formula.
#' @param G An integer vector of the numbers of components to fit, each at
#'  least 2. A single value fits one model. Default is \code{2:5}.
#' @param family A character string, one of \code{"gaussian"},
#'  \code{"poisson"}, or \code{"binomial"}. Default is \code{"gaussian"}.
#' @param common A character vector of predictor names (as they appear in
#'  \code{formula}) whose effect is the same in every component. Default is
#'  \code{character(0)}: all predictors are heterogeneous.
#' @param control A control object of class "FMRControl" generated by
#'  \code{\link{fmr_control}}. The settings \code{alpha}, \code{direction},
#'  \code{parallel}, and \code{verbose} only apply to \code{\link{stepFMR}}
#'  and are ignored here. Default is \code{fmr_control()}.
#'
#' @return A list of class \code{fitFMR} containing:
#'  \item{call}{The matched call.}
#'  \item{formula}{The model formula. For binomial responses the response
#'  is reduced to the success count (the trial counts are carried
#'  internally).}
#'  \item{family}{The response family used.}
#'  \item{G_values}{The numbers of components fit, sorted.}
#'  \item{common}{Predictors with a shared (homogeneous) coefficient.}
#'  \item{heterogeneous}{Predictors with component-specific coefficients
#'  (the intercept is always component-specific and not listed).}
#'  \item{fits}{A named list (\code{"G2"}, \code{"G3"}, ...) of
#'  \code{fit_fmr} objects, one per value of \code{G}.}
#'  \item{table}{A data frame with one row per \code{G}: \code{G},
#'  \code{loglik}, \code{num_parameters}, \code{bic}, \code{iterations},
#'  and \code{converged}.}
#'  \item{selected_G}{The \code{G} with the lowest BIC.}
#'  \item{best_fit}{The \code{fit_fmr} object at \code{selected_G}.}
#'  \item{control}{The \code{FMRControl} object used.}
#'
#' @seealso \code{\link{stepFMR}} to also select predictors and effect types,
#'  \code{\link{fmr_control}}, \code{\link{match_groups}}.
#' @export
#'
#' @examples
#' set.seed(1)
#'
#' # Simulate data
#' n <- 500
#' pi <- c(0.3, 0.7)
#' z <- sample(1:2, n, replace = TRUE, prob = pi)
#' x1 <- rnorm(n)
#' x2 <- rnorm(n)
#'
#' # True parameters for 2 group mixture model (x2 has a common effect)
#' beta <- rbind(
#'   g1 = c(intercept = -3, x1 = -2, x2 = 1.5),
#'   g2 = c(intercept = 3, x1 = 2, x2 = 1.5)
#' )
#' sigma <- c(1, 0.5)
#'
#' # Generate linear predictor and corresponding response y
#' eta <- beta[z, "intercept"] + beta[z, "x1"] * x1 + beta[z, "x2"] * x2
#' y <- rnorm(n, mean = eta, sd = sigma[z])
#' dat <- data.frame(y = y, x1 = x1, x2 = x2)
#'
#' # All predictors heterogeneous, number of components chosen by BIC
#' fitFMR(formula = y ~ x1 + x2, data = dat, G = 2:3)
#'
#' # x2 has the same effect in every component, and G is known to be 2
#' fit <- fitFMR(formula = y ~ x1 + x2, data = dat, G = 2, common = "x2")
#' summary(fit)
#'
fitFMR <- function(
  formula,
  data,
  G = 2:5,
  family = "gaussian",
  common = character(0),
  control = fmr_control()
) {
  collection <- checkmate::makeAssertCollection()
  checkmate::assert_formula(formula, add = collection)
  checkmate::assert_data_frame(data, add = collection)
  checkmate::assert_integerish(G,
    lower = 2, min.len = 1, any.missing = FALSE, add = collection
  )
  checkmate::assert_choice(family,
    choices = c("gaussian", "poisson", "binomial"),
    add = collection
  )
  checkmate::assert_character(common, any.missing = FALSE, add = collection)
  checkmate::assert_class(control, "FMRControl", add = collection)

  if (!collection$isEmpty()) {
    err_messages <- paste0("- ", collection$getMessages(), collapse = "\n")
    stop(err_messages, call. = FALSE)
  }

  G <- sort(unique(as.integer(G)))
  common <- unique(common)

  formula <- stats::formula(stats::terms(formula, data = data))

  if (family == "binomial") {
    coerced <- coerce_binomial_formula(formula, data)
    formula <- coerced$formula
    data <- coerced$data
  }

  unknown <- setdiff(common, get_predictors(formula))
  if (length(unknown) > 0L) {
    stop(sprintf(
      "`common` must name predictors in the formula. Not found: %s.",
      paste(unknown, collapse = ", ")
    ), call. = FALSE)
  }

  model <- FMRModel$new(
    formula = formula,
    data = data,
    G_values = G,
    family = family,
    control = control
  )

  prepared_data <- prepare_data(
    model,
    included = model$predictors,
    common = common
  )
  fits <- fit_across_G(model, prepared_data)
  names(fits) <- paste0("G", G)

  fit_table <- do.call(rbind, lapply(fits, function(fit) {
    data.frame(
      G = fit$G,
      loglik = fit$loglik,
      num_parameters = fit$num_parameters,
      bic = fit$bic,
      iterations = fit$iterations,
      converged = fit$converged,
      stringsAsFactors = FALSE
    )
  }))
  rownames(fit_table) <- NULL

  best_fit <- select_best_G(fits, criterion = "bic")

  not_converged <- fit_table$G[!fit_table$converged]
  if (length(not_converged) > 0L) {
    warning(sprintf(
      "EM did not converge for G = %s. Consider increasing `max_iter`.",
      paste(not_converged, collapse = ", ")
    ), call. = FALSE)
  }

  out <- list(
    call = match.call(),
    formula = formula,
    family = family,
    G_values = G,
    common = common,
    heterogeneous = setdiff(model$predictors, common),
    fits = fits,
    table = fit_table,
    selected_G = best_fit$G,
    best_fit = best_fit,
    control = control
  )

  class(out) <- "fitFMR"
  out
}
